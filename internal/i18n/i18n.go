// T returns the message for key in lang, falling back to English, then to the key itself.
func T(lang, key string) string {
	if m, ok := messages[lang][key]; ok {
		return m
	}
	if m, ok := messages["en"][key]; ok {
		return m
	}
	return key
}

// All returns every message for lang (used to embed both languages in the HTML report).
// Has tells whether key exists (optional texts, such as the report's column explanations).
func Has(key string) bool { _, ok := messages["en"][key]; return ok }

func All(lang string) map[string]string { return messages[lang] }

// Normalize maps any locale string (pt_BR.UTF-8, pt-br, en-US...) to en or pt-BR.
func Normalize(s string) string {
	if strings.HasPrefix(strings.ToLower(s), "pt") {
		return "pt-BR"
	}
	return "en"
}

// Detect reads LANG/LC_ALL first, then the OS (Windows user locale).
func Detect() string {
	for _, k := range []string{"LC_ALL", "LC_MESSAGES", "LANG"} {
		if v := os.Getenv(k); v != "" && v != "C" && v != "POSIX" {
			return Normalize(v)
		}
	}
	return Normalize(osLocale())
}
